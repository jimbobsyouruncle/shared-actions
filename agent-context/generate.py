#!/usr/bin/env python3
"""Generate small, agent-friendly repository context files.

This script writes two files into the output directory:

* ``REPO_MAP.md`` - a directory-grouped list of the tracked files, one line per
  file, with a short description.
* ``CODE_INDEX.md`` - a per-file index of code structure (signatures, function
  names, service names, job ids, and so on) without any file bodies.

The file list comes from ``git ls-files`` only, so only tracked files are
considered and the order is deterministic. The output contains no timestamps
and no commit SHAs, so the same input tree always produces byte-identical
output.

If either generated file exceeds ``max_bytes`` the script exits non-zero and
names the offending file and its size. It never truncates silently.

Python 3 standard library only.
"""

import argparse
import ast
import os
import re
import subprocess
import sys

EXCLUDED_DIRS = {".git"}

# A short, stable header shared by both generated files. The size limit is
# included, but no timestamps or commit SHAs, so the output stays deterministic.
def make_header(max_bytes):
    """Return the shared generated-file header, including the size limit."""
    return (
        "<!-- Generated by the agent-context composite action (generate.py).\n"
        "     Source: `git ls-files` output. Do not edit by hand.\n"
        "     Size limit: %d bytes per file (max-bytes).\n"
        "     No timestamps or commit SHAs are included; output is deterministic. -->\n"
        % max_bytes
    )

MAX_DESCRIPTION = 100


# --------------------------------------------------------------------------- #
# Repository discovery
# --------------------------------------------------------------------------- #
def list_tracked_files(repo_root):
    """Return the sorted list of files tracked by git in ``repo_root``."""
    result = subprocess.run(
        ["git", "-C", repo_root, "ls-files", "-z"],
        check=True,
        stdout=subprocess.PIPE,
    )
    names = result.stdout.decode("utf-8", "surrogateescape").split("\0")
    return sorted(name for name in names if name)


def is_excluded(path):
    """Return True when ``path`` (POSIX-style, repo-relative) is excluded."""
    parts = path.split("/")
    if any(part in EXCLUDED_DIRS for part in parts):
        return True

    name = parts[-1]

    if name.startswith("CONSOLIDATED_") and name.endswith(".md"):
        return True
    if name in ("REPO_MAP.md", "CODE_INDEX.md"):
        return True

    if name != ".env.example":
        if name == ".env" or name.startswith(".env."):
            return True

    for suffix in (".pem", ".key", ".log"):
        if name.endswith(suffix):
            return True
    if name.startswith("id_"):
        return True

    return False


def is_unsafe_path(repo_root, rel_path):
    """Return True when ``rel_path`` is a symlink or resolves outside the root.

    ``rel_path`` is repo-relative (POSIX-style). Both checks use metadata only
    (``os.lstat`` / ``os.path.realpath``) and never open the file, so a tracked
    symlink can never leak content from outside the repository.
    """
    joined = os.path.join(repo_root, rel_path)
    if os.path.islink(joined):
        return True
    real_root = os.path.realpath(repo_root)
    real_path = os.path.realpath(joined)
    if real_path != real_root and not real_path.startswith(real_root + os.sep):
        return True
    return False


def is_binary(data):
    """Return True when ``data`` looks like binary (NUL byte in first 8 KB)."""
    return b"\x00" in data[:8192]


def read_text(path):
    """Return decoded text, or None when the file is missing or binary."""
    try:
        with open(path, "rb") as handle:
            data = handle.read()
    except OSError:
        return None
    if is_binary(data):
        return None
    return data.decode("utf-8", "replace")


# --------------------------------------------------------------------------- #
# Descriptions
# --------------------------------------------------------------------------- #
def clean_description(text):
    """Normalise a description to one line, no backticks, <= 100 characters."""
    if not text:
        return ""
    line = text.replace("`", "")
    line = " ".join(line.split())
    if len(line) > MAX_DESCRIPTION:
        line = line[:MAX_DESCRIPTION].rstrip()
    return line


def _first_heading(text):
    for raw in text.splitlines():
        if raw.startswith("# "):
            return raw[2:]
    return None


def _first_docstring_line(text):
    try:
        module = ast.parse(text)
    except (SyntaxError, ValueError):
        return None
    docstring = ast.get_docstring(module)
    if not docstring:
        return None
    return docstring.splitlines()[0]


def _first_shell_comment(text):
    lines = text.splitlines()
    index = 1 if lines and lines[0].startswith("#!") else 0
    for raw in lines[index:]:
        stripped = raw.strip()
        if not stripped:
            continue
        if stripped.startswith("#"):
            comment = stripped.lstrip("#").strip()
            # Skip decorative divider lines such as "# ----------".
            if comment and any(char.isalnum() for char in comment):
                return comment
            continue
        break
    return None


def _yaml_name_or_comment(text):
    for raw in text.splitlines():
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if stripped.startswith("name:"):
            return stripped[len("name:"):].strip()
        break
    for raw in text.splitlines():
        stripped = raw.strip()
        if not stripped.startswith("#"):
            continue
        comment = stripped.lstrip("#").strip()
        # Skip decorative divider lines such as "# ----------".
        if comment and any(char.isalnum() for char in comment):
            return comment
    return None


def describe(rel_path, text):
    """Return a one-line description for ``rel_path`` based on its extension."""
    lower = rel_path.lower()
    if lower.endswith(".md"):
        return clean_description(_first_heading(text))
    if lower.endswith(".py"):
        return clean_description(_first_docstring_line(text))
    if lower.endswith(".sh"):
        return clean_description(_first_shell_comment(text))
    if lower.endswith(".yml") or lower.endswith(".yaml"):
        return clean_description(_yaml_name_or_comment(text))
    return ""


# --------------------------------------------------------------------------- #
# REPO_MAP.md
# --------------------------------------------------------------------------- #
def is_github_path(rel_path):
    """Return True when ``rel_path`` lives under ``.github/``."""
    return rel_path == ".github" or rel_path.startswith(".github/")


def build_repo_map(entries, max_bytes):
    """Build the REPO_MAP.md content from ``(path, description)`` entries.

    Entries are grouped by their directory so each directory heading appears
    exactly once and every file sits under its own directory's heading. The
    repository root is emitted first as its own group.
    """
    groups = {}
    for path, description in entries:
        directory = os.path.dirname(path)
        if is_github_path(path):
            # `.github/` paths are listed as paths only, per the spec.
            description = ""
        groups.setdefault(directory, []).append((path, description))

    # Root-level files first, then the remaining directories in sorted order.
    directories = sorted(groups, key=lambda name: (name != "", name))

    lines = ["# Repository map", "", make_header(max_bytes), ""]
    for directory in directories:
        lines.append("## %s" % (directory if directory else "."))
        lines.append("")
        for path, description in groups[directory]:
            if description:
                lines.append("- %s - %s" % (path, description))
            else:
                lines.append("- %s" % path)
    lines.append("")
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# CODE_INDEX.md helpers
# --------------------------------------------------------------------------- #
def format_arguments(arguments):
    """Return a comma-separated parameter name list, without default values."""
    names = []
    for arg in list(getattr(arguments, "posonlyargs", [])) + list(arguments.args):
        names.append(arg.arg)
    if arguments.vararg:
        names.append("*" + arguments.vararg.arg)
    elif arguments.kwonlyargs:
        names.append("*")
    for arg in arguments.kwonlyargs:
        names.append(arg.arg)
    if arguments.kwarg:
        names.append("**" + arguments.kwarg.arg)
    return ", ".join(names)


def _base_name(node):
    """Return a readable name for a class base expression."""
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    return "*"


def class_signature(node):
    """Return ``class Name(bases)`` using base names only."""
    bases = ", ".join(_base_name(base) for base in node.bases if not isinstance(base, ast.Starred))
    return "class %s(%s)" % (node.name, bases)


def node_signature(node):
    """Return a signature string for a def/class node, without defaults."""
    if isinstance(node, ast.ClassDef):
        return class_signature(node)
    prefix = "async def " if isinstance(node, ast.AsyncFunctionDef) else "def "
    return "%s%s(%s)" % (prefix, node.name, format_arguments(node.args))


def _python_symbols(node, lines, indent):
    """Append symbol lines for ``node`` (module or class body) to ``lines``."""
    prefix = " " * indent
    for child in node.body:
        if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            lines.append("%s- %s" % (prefix, node_signature(child)))
            if isinstance(child, ast.ClassDef):
                _python_symbols(child, lines, indent + 2)


def index_python(text):
    """Return a list of signature lines for a Python source file."""
    module = ast.parse(text)
    lines = []
    _python_symbols(module, lines, 0)
    return lines


SHELL_FUNCTION = re.compile(
    r"^\s*(?:function\s+)?"
    r"([A-Za-z_][A-Za-z0-9_]*)\s*\(\s*\)\s*(?:\{|$)"
)
SHELL_KEYWORD_FUNCTION = re.compile(r"^\s*function\s+([A-Za-z_][A-Za-z0-9_]*)\s*(?:\{|$)")


def index_shell(text):
    """Return a list of function names found in a shell script."""
    names = []
    for raw in text.splitlines():
        match = SHELL_FUNCTION.match(raw) or SHELL_KEYWORD_FUNCTION.match(raw)
        if not match:
            continue
        name = match.group(1)
        if name not in names:
            names.append(name)
    return ["- %s()" % name for name in names]


def _iter_yaml_keys(text):
    """Yield ``(indent, key)`` for every mapping key found by indentation scan."""
    for raw in text.splitlines():
        if not raw or raw[0] == "\t":
            continue
        stripped = raw.strip()
        if not stripped or stripped.startswith("#") or stripped.startswith("- "):
            continue
        if ":" not in stripped:
            continue
        key = stripped.split(":", 1)[0].strip()
        if not key:
            continue
        if key[0] in "'\"":
            key = key[1:].split(key[0])[0]
        yield len(raw) - len(raw.lstrip(" ")), key


def _children_keys(text, parent):
    """Return the immediate child keys of the first ``parent`` mapping key."""
    lines = list(_iter_yaml_keys(text))
    for index, (indent, key) in enumerate(lines):
        if key != parent:
            continue
        child_indent = None
        children = []
        for later_indent, later_key in lines[index + 1:]:
            if later_indent <= indent:
                break
            if child_indent is None:
                child_indent = later_indent
            if later_indent == child_indent:
                children.append(later_key)
        return children
    return []


def index_yaml_top_keys(text):
    """Return top-level ``key:`` values using a minimal indentation scan."""
    keys = []
    for indent, key in _iter_yaml_keys(text):
        if indent == 0 and key not in keys:
            keys.append(key)
    return ["- %s" % key for key in keys]


def index_compose_services(text):
    """Return service names from a docker-compose style file."""
    return ["- %s" % name for name in _children_keys(text, "services")]


def index_workflow_jobs(text):
    """Return job ids from a workflow file."""
    return ["- %s" % name for name in _children_keys(text, "jobs")]


def index_dockerfile(text):
    """Return FROM lines and named stage names from a Dockerfile."""
    lines = []
    for raw in text.splitlines():
        stripped = raw.strip()
        if not stripped.lower().startswith("from "):
            continue
        lines.append("- %s" % stripped)
        parts = stripped.split()
        lowered = [part.lower() for part in parts]
        if "as" in lowered:
            index = lowered.index("as")
            if index + 1 < len(parts):
                lines.append("- stage: %s" % parts[index + 1])
    return lines


def index_text_file(rel_path, text):
    """Dispatch to the correct indexer, or return None when not a code file."""
    name = os.path.basename(rel_path).lower()
    posix = rel_path.replace("\\", "/")
    if name.endswith(".py"):
        return index_python(text)
    if name.endswith(".sh"):
        return index_shell(text)
    if name.startswith("dockerfile"):
        return index_dockerfile(text)
    if ".github/workflows/" in posix and (name.endswith(".yml") or name.endswith(".yaml")):
        return index_workflow_jobs(text)
    if name.endswith(".yml") or name.endswith(".yaml"):
        if "compose" in name:
            return index_compose_services(text)
        return index_yaml_top_keys(text)
    return None


def build_code_index(entries, max_bytes):
    """Build the CODE_INDEX.md content from ``(path, text)`` entries."""
    lines = ["# Code index", "", make_header(max_bytes), ""]
    for path, text in entries:
        lines.append("## %s" % path)
        try:
            symbols = index_text_file(path, text)
        except Exception:
            symbols = None
        if symbols is None:
            lines.append("- (unparsed)")
        elif not symbols:
            lines.append("- (no symbols)")
        else:
            lines.extend(symbols)
        lines.append("")
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# Size limit
# --------------------------------------------------------------------------- #
def enforce_limit(path, max_bytes):
    """Exit non-zero when ``path`` is larger than ``max_bytes``."""
    size = os.path.getsize(path)
    if size > max_bytes:
        sys.stderr.write(
            "error: %s is %d bytes, which exceeds the limit of %d bytes "
            "(max-bytes). Reduce the file list or raise max-bytes.\n"
            % (path, size, max_bytes)
        )
        raise SystemExit(1)


# --------------------------------------------------------------------------- #
# Entry point
# --------------------------------------------------------------------------- #
def generate(repo_root, output_dir, max_bytes, parse_repo=True):
    """Generate both files and return ``(repo_map_path, code_index_path)``."""
    repo_root = os.path.abspath(repo_root)
    output_dir = os.path.abspath(output_dir)
    os.makedirs(output_dir, exist_ok=True)

    descriptions = []
    code_entries = []

    if parse_repo:
        for rel_path in list_tracked_files(repo_root):
            if is_excluded(rel_path):
                continue
            if is_unsafe_path(repo_root, rel_path):
                continue
            text = read_text(os.path.join(repo_root, rel_path))
            if text is None:
                continue
            descriptions.append((rel_path, describe(rel_path, text)))
            try:
                is_code = index_text_file(rel_path, text) is not None
            except Exception:
                is_code = True
            if is_code:
                code_entries.append((rel_path, text))

    repo_map_path = os.path.join(output_dir, "REPO_MAP.md")
    code_index_path = os.path.join(output_dir, "CODE_INDEX.md")

    with open(repo_map_path, "w", encoding="utf-8") as handle:
        handle.write(build_repo_map(descriptions, max_bytes))
    with open(code_index_path, "w", encoding="utf-8") as handle:
        handle.write(build_code_index(code_entries, max_bytes))

    enforce_limit(repo_map_path, max_bytes)
    enforce_limit(code_index_path, max_bytes)

    return repo_map_path, code_index_path


def main(argv=None):
    """Parse arguments and run the generator."""
    parser = argparse.ArgumentParser(
        description="Generate REPO_MAP.md and CODE_INDEX.md for agent context."
    )
    parser.add_argument("--root", default=".", help="repository root (default: .)")
    parser.add_argument("--output-dir", default=".", help="output directory (default: .)")
    parser.add_argument(
        "--max-bytes", type=int, default=20480, help="size limit per file"
    )
    args = parser.parse_args(argv)

    repo_map_path, code_index_path = generate(
        args.root, args.output_dir, args.max_bytes
    )
    print(
        "wrote %s (%d bytes) and %s (%d bytes)"
        % (
            repo_map_path,
            os.path.getsize(repo_map_path),
            code_index_path,
            os.path.getsize(code_index_path),
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
